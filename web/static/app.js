  async function saveApproval(event) {
    event.preventDefault();
    elements.approvalFeedback.textContent = "";
    elements.approvalFeedback.classList.remove("error");
    const data = new FormData(elements.approvalForm);
    const payload = Object.fromEntries(data.entries());
    try {
      const response = await fetchJSON("/api/approved-agents", {
        method: "POST",
        headers: { "Content-Type": "application/json", "X-Agent-Governance-Admin": "local-ui" },
        body: JSON.stringify(payload)
      });
      state.discovery = response.discovery;
      renderDiscoveries(response.discovery);
      resetApprovalForm();
      await loadApprovals();
      elements.approvalFeedback.textContent = t("approvalSaved");
    } catch (error) {
      elements.approvalFeedback.textContent = error.message;
      elements.approvalFeedback.classList.add("error");
    }
  }
  async function deleteApproval(approval) {
    if (!window.confirm(t("confirmRemove"))) return;
    try {
      const response = await fetchJSON(`/api/approved-agents/${encodeURIComponent(approval.id)}`, { method: "DELETE", headers: { "X-Agent-Governance-Admin": "local-ui" } });
      state.discovery = response.discovery;
      renderDiscoveries(response.discovery);
      await loadApprovals();
      elements.approvalFeedback.textContent = t("approvalRemoved");
    } catch (error) {
      elements.approvalFeedback.textContent = error.message;
    }
  }
